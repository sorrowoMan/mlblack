def load_scaffold_spec(path: str | Path) -> ScaffoldSpec:
    p = Path(path)
    payload = json.loads(p.read_text(encoding="utf-8-sig"))
    return build_scaffold_spec(payload)


def _resolve_state_store_cfg(
    train_spec: TrainStageSpec,
) -> tuple[Mapping[str, Any] | None, Mapping[str, Any] | None]:
    state_backend_cfg = None if train_spec.state_backend is None else dict(train_spec.state_backend)
    context_store_cfg: Mapping[str, Any] | None = None
    snapshot_store_cfg: Mapping[str, Any] | None = None
    if state_backend_cfg is not None:
        context_store_cfg = (
            None if state_backend_cfg.get("context") is None else dict(state_backend_cfg.get("context", {}))
        )
        snapshot_store_cfg = None if state_backend_cfg.get("snapshot") is None else dict(
            state_backend_cfg.get("snapshot", {})
        )
    return context_store_cfg, snapshot_store_cfg


def _build_semantic_flow_spec(
    spec: ScaffoldSpec,
    *,
    model_spec: ModelSpec | None = None,
    run_name: str | None = None,
    output_dir: str | None = None,
    context_store_cfg: Mapping[str, Any] | None = None,
    snapshot_store_cfg: Mapping[str, Any] | None = None,
) -> SemanticTrainFlowSpec:
    resolved_execution = coerce_execution_spec(
        spec.train.execution,
        fallback_backend=str(spec.train.portfolio_parallel_mode),
        fallback_max_workers=spec.train.portfolio_max_workers,
        fallback_fail_fast=bool(spec.train.portfolio_fail_fast),
        fallback_gpu_strategy=str(spec.train.portfolio_gpu_strategy),
        fallback_gpu_devices=tuple(spec.train.portfolio_gpu_devices),
    )
    trainer_assembly = TrainerAssemblySpec(
        trainer_key=spec.train.trainer_key,
        trainer_params=dict(spec.train.trainer_params),
        pipeline_key=spec.train.pipeline_key,
        pipeline_params=dict(spec.train.pipeline_params),
        biases=_to_bias_specs(spec.train.biases),
    )

    semantic_assembly = FlowAssemblySpec(
        trainer=trainer_assembly,
        numericizer=NumericizerSpec(
            key=str(spec.train.numericizer_key),
            params=dict(spec.train.numericizer_params),
        ),
        capabilities=_to_capability_specs(spec.train.capabilities),
    )

    flow_spec = SemanticTrainFlowSpec(
        assembly=semantic_assembly,
        execution=resolved_execution,
        training_init=None if spec.train.training_init is None else dict(spec.train.training_init),
        eval_splits=tuple(spec.train.eval_splits),
        output_dir=str(output_dir or spec.train.output_dir),
        save_artifact=True,
        save_report=True,
        model_spec=model_spec,
        capability_strict=bool(spec.train.capability_strict),
        run_name=str(run_name or spec.train.run_name),
        context_store=context_store_cfg,
        snapshot_store=snapshot_store_cfg,
        portfolio_parallel_mode=str(spec.train.portfolio_parallel_mode),
        portfolio_max_workers=spec.train.portfolio_max_workers,
        portfolio_fail_fast=bool(spec.train.portfolio_fail_fast),
        portfolio_gpu_strategy=str(spec.train.portfolio_gpu_strategy),
        portfolio_gpu_devices=tuple(spec.train.portfolio_gpu_devices),
    )
    return flow_spec


def run_project_scaffold_portfolio(spec: ScaffoldSpec) -> TrainPortfolioResult:
    model_specs = _to_model_specs(spec.train.model_specs)
    if not model_specs:
        raise ValueError("run_project_scaffold_portfolio requires non-empty train.model_specs")

    bundle = _table_to_bundle(spec.data)
    context_store_cfg, snapshot_store_cfg = _resolve_state_store_cfg(spec.train)
    base_flow_spec = _build_semantic_flow_spec(
        spec,
        context_store_cfg=context_store_cfg,
        snapshot_store_cfg=snapshot_store_cfg,
    )
    return run_semantic_portfolio_flow(
        bundle,
        spec=base_flow_spec,
        model_specs=model_specs,
    )


def run_project_scaffold(spec: ScaffoldSpec) -> TrainFlowResult:
    if spec.train.model_specs:
        portfolio = run_project_scaffold_portfolio(spec)
        best_model_id = portfolio.summary.get("best_model_id")
        selected_id = str(best_model_id) if best_model_id is not None else next(iter(portfolio.runs.keys()))
        if selected_id not in portfolio.runs:
            selected_id = next(iter(portfolio.runs.keys()))
        result = portfolio.runs[selected_id]
        result.report["portfolio"] = dict(portfolio.summary)
        return result

    bundle = _table_to_bundle(spec.data)
    context_store_cfg, snapshot_store_cfg = _resolve_state_store_cfg(spec.train)
    flow_spec = _build_semantic_flow_spec(
        spec,
        model_spec=_to_model_spec(spec.train.model_spec),
        context_store_cfg=context_store_cfg,
        snapshot_store_cfg=snapshot_store_cfg,
    )
    return run_semantic_train_flow(bundle, spec=flow_spec)












