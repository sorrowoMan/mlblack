_ENV_BRACED_PATTERN = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")


def _expand_env_refs(value: str) -> str:
    """Expand `%VAR%`, `$VAR`, and `${VAR}` references in string values."""
    text = os.path.expandvars(str(value))

    def _replace(match: re.Match[str]) -> str:
        key = str(match.group(1))
        raw = os.environ.get(key)
        if raw is None:
            return match.group(0)
        return str(raw)

    return _ENV_BRACED_PATTERN.sub(_replace, text)


def _as_name_tuple(value: Any) -> tuple[str, ...]:
    if value is None:
        return tuple()
    if isinstance(value, str):
        text = str(value).strip()
        return tuple() if not text else (text,)
    out: list[str] = []
    for item in value:
        key = str(item).strip()
        if key:
            out.append(key)
    return tuple(out)


